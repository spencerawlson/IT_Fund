// The generated counts module must match a fresh build, and the numbers
// behind the landing page's claims must be the ones the data actually has.
import { describe, it, expect } from 'vitest';
import { readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildCounts, plus } from './generate-counts.mjs';
import { COUNTS } from '../src/data/counts.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

describe('generate-counts', () => {
  it('committed counts match a fresh build', () => {
    expect(COUNTS).toEqual(buildCounts());
    expect(readFileSync(join(ROOT, 'src', 'data', 'counts.js'), 'utf8')).toContain('GENERATED by scripts/generate-counts.mjs');
  });

  it('formats "N+" figures by rounding down', () => {
    expect(plus(3075)).toBe('3,000+');
    expect(plus(980)).toBe('900+');
    expect(plus(124)).toBe('100+');
    expect(plus(61)).toBe('60+');
    expect(plus(37)).toBe('30+');
    expect(plus(10)).toBe('10+');
    expect(plus(9)).toBe('9');
  });

  it('pins the numbers the landing page claims', () => {
    // Totals across the catalogue.
    expect(COUNTS.totalCards).toBe(3145);
    expect(COUNTS.totalDecks).toBe(222);
    // Labs: 32 mock + 29 docker (backend/labs/registry.list_labs()).
    expect(COUNTS.labs).toBe(61);
    // The Security+ path is the cyber track: 37 lessons, 980 cards.
    // (The landing page once claimed "40 lessons" — the data says 37.)
    expect(COUNTS.tracks.cyber.decks).toBe(37);
    expect(COUNTS.tracks.cyber.cards).toBe(980);
    // The Linux track really does have ten decks.
    expect(COUNTS.tracks.linux.decks).toBe(10);
  });
});
