// Marketing numbers, generated from the data — the single source of truth
// for every count the copy states (audit F-14). Hand-written numbers drift:
// the landing page once claimed "40 lessons" for Security+ when the cyber
// track holds 37, and "800+ flashcards" when the catalogue holds 3,075.
//
// Run `node scripts/generate-counts.mjs` after any curriculum or lab change;
// scripts/generate-counts.test.js fails if the committed file drifts.
// The app imports the generated src/data/counts.js — never a literal.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { tracks, allDecks, allCards } from './export-content-lib.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

/** Round a count down to a presentable "N+" figure, in the copy's own style. */
export function plus(n) {
  if (n >= 1000) return `${(Math.floor(n / 1000) * 1000).toLocaleString('en-US')}+`;
  if (n >= 100) return `${Math.floor(n / 100)}00+`;
  if (n >= 10) return `${Math.floor(n / 10)}0+`;
  return `${n}`;
}

/** Lab definitions live in Python; each is one `LabDefinition(` call. The
 * authority is the backend registry (`labs.registry.list_labs()`); this
 * scan must agree with it — the test pins the current total. */
function countLabs() {
  const dir = join(ROOT, 'backend', 'labs', 'definitions');
  let n = 0;
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.py'))) {
    n += (readFileSync(join(dir, file), 'utf8').match(/LabDefinition\(/g) || []).length;
  }
  return n;
}

export function buildCounts() {
  const perTrack = {};
  for (const t of tracks) {
    const decks = t.tiers.flatMap((tier) => tier.decks);
    const cards = decks.reduce((s, d) => s + d.cards.length, 0);
    // A track's decks ARE its lessons (src/data/catalog/courses.js).
    perTrack[t.id] = { decks: decks.length, cards, decksPlus: plus(decks.length), cardsPlus: plus(cards) };
  }
  const labs = countLabs();
  return {
    tracks: perTrack,
    totalCards: allCards.length,
    totalCardsPlus: plus(allCards.length),
    totalDecks: allDecks.length,
    totalDecksPlus: plus(allDecks.length),
    labs,
    labsPlus: plus(labs),
  };
}

const HEADER = `// GENERATED by scripts/generate-counts.mjs — do not edit by hand.
// Source of truth: src/data/academy/*.js (via scripts/export-content-lib.mjs)
// and backend/labs/definitions/*.py. Regenerate with:
//   node scripts/generate-counts.mjs
// Marketing copy must read these numbers, never a literal (audit F-14).
// A track's decks are its lessons.
`;

function main() {
  const counts = buildCounts();
  const out = `${HEADER}\nexport const COUNTS = ${JSON.stringify(counts, null, 2)};\n`;
  writeFileSync(join(ROOT, 'src', 'data', 'counts.js'), out);
  console.log(
    `counts: ${counts.totalCards} cards (${counts.totalCardsPlus}), ${counts.totalDecks} decks, ${counts.labs} labs (${counts.labsPlus})`,
  );
}

// Only regenerate when run directly (`node scripts/generate-counts.mjs`);
// importing this module (tests, other scripts) must not rewrite the file.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
