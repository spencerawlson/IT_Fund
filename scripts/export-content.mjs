// Regenerate the content artifacts after any curriculum edit:
//   node scripts/export-content.mjs
//
// Writes backend/data/content.json (full dataset, served gated by the API)
// and src/data/content-public.js (public subset only, bundled with the app).
// Run this whenever src/data/academy/*.js, src/data/catalog/lessons/*.js,
// src/data/moduleNotes/*.js, src/data/academy/interactive.js or
// src/data/cipherNotes.js changes. scripts/export-content.test.js fails if
// the committed artifacts drift from the sources.
import { writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildContentJson, buildPublicData, census } from './export-content-lib.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

const HEADER = `// GENERATED by scripts/export-content.mjs — do not edit by hand.
// Source of truth: src/data/academy/*.js, src/data/catalog/lessons/*.js,
// src/data/moduleNotes/*.js, src/data/academy/interactive.js, src/data/cipherNotes.js.
// Regenerate with: node scripts/export-content.mjs
//
// PUBLIC SUBSET ONLY: full structure (tracks/tiers/decks, titles, summaries,
// tags, card ids + counts) plus the FREE tier's card bodies, lesson bodies,
// puzzles and cipher notes. Premium bodies NEVER appear in this file — they
// are served by GET /api/content/* (backend/content.py) after an entitlement
// check. If you can read a premium lesson or answer in here, the export is
// broken: fix scripts/export-content-lib.mjs, do not hand-edit this file.
`;

function main() {
  const full = buildContentJson();
  mkdirSync(join(ROOT, 'backend', 'data'), { recursive: true });
  writeFileSync(
    join(ROOT, 'backend', 'data', 'content.json'),
    `${JSON.stringify(full, null, 2)}\n`,
    'utf8',
  );

  const pub = buildPublicData();
  const pubSource =
    `${HEADER}\nexport const CONTENT_VERSION = ${pub.version};\n\n` +
    `export const tracks = ${JSON.stringify(pub.tracks, null, 2)};\n\n` +
    `export const freeLessonContent = ${JSON.stringify(pub.freeLessonContent, null, 2)};\n\n` +
    `export const freeCipherNotes = ${JSON.stringify(pub.freeCipherNotes, null, 2)};\n`;
  writeFileSync(join(ROOT, 'src', 'data', 'content-public.js'), pubSource, 'utf8');

  const c = census();
  // eslint-disable-next-line no-console
  console.log(
    `content export: ${c.tracks} tracks, ${c.decks} decks, ${c.cards} cards, ` +
      `${c.lessonsWithContent}/${c.lessons} lessons with content, ${c.notes} notes, ` +
      `${c.puzzles} puzzles — free tier: ${c.freeDecks} decks (${c.freeCards} cards), ` +
      `${c.freeLessons} lessons`,
  );
}

main();
