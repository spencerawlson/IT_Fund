export function getModulesForLab(labId) {
  return LAB_LINKS.filter((l) => l.labId === labId)
    .map((l) => {
      const mod = modules.find((m) => m.id === l.moduleId);
      return mod ? { moduleId: l.moduleId, moduleTitle: mod.title, concept: l.concept } : null;
    })
    .filter(Boolean);
}

export function getLabForModule(moduleId) {
  const seen = new Set();
  const result = [];
  LAB_LINKS.forEach((l) => {
    if (l.moduleId === moduleId && !seen.has(l.labId)) {
      seen.add(l.labId);
      result.push({ labId: l.labId, label: LAB_LABELS[l.labId], concept: l.concept });
    }
  });
  return result;
}